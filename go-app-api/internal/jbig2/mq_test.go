package jbig2

import (
	"bytes"
	"testing"
)

// TestMQDecoderAnnexH2 is the arithmetic decoder test sequence of T.88
// Annex H.2: 256 decisions in one context.
func TestMQDecoderAnnexH2(t *testing.T) {
	in := []byte{0x84, 0xC7, 0x3B, 0xFC, 0xE1, 0xA1, 0x43, 0x04, 0x02, 0x20, 0x00, 0x00,
		0x41, 0x0D, 0xBB, 0x86, 0xF4, 0x31, 0x7F, 0xFF, 0x88, 0xFF, 0x37, 0x47, 0x1A, 0xDB,
		0x6A, 0xDF, 0xFF, 0xAC}
	want := []byte{0x00, 0x02, 0x00, 0x51, 0x00, 0x00, 0x00, 0xC0, 0x03, 0x52, 0x87, 0x2A,
		0xAA, 0xAA, 0xAA, 0xAA, 0x82, 0xC0, 0x20, 0x00, 0xFC, 0xD7, 0x9E, 0xF6, 0xBF, 0x7F,
		0xED, 0x90, 0x4F, 0x46, 0xA3, 0xBF}
	d := newMQDecoder(in)
	cx := make(contexts, 1)
	got := make([]byte, len(want))
	for i := 0; i < len(want)*8; i++ {
		got[i>>3] |= byte(d.decode(cx, 0)) << (7 - i&7)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("got  % X\nwant % X", got, want)
	}
}
